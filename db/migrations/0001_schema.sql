-- Altimeter: readiness and score-trust console for English test-prep institutions.
-- Lives in its own schema `alt` inside a shared Supabase project; nothing here touches other schemas.
--
-- Roles: the app logs in as `alt_app` (owns nothing, NOINHERIT) and, inside each request transaction,
-- switches to exactly one of:
--   alt_user    signed-in people; row-level security on the verified JWT claims decides what they see
--   alt_worker  queue consumers; may only call the worker functions
--   alt_api     partner systems with an API key; may only call the api_* functions

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'alt_user') then create role alt_user nologin noinherit; end if;
  if not exists (select 1 from pg_roles where rolname = 'alt_worker') then create role alt_worker nologin noinherit; end if;
  if not exists (select 1 from pg_roles where rolname = 'alt_api') then create role alt_api nologin noinherit; end if;
  if not exists (select 1 from pg_roles where rolname = 'alt_app') then create role alt_app login noinherit; end if;
end $$;
grant alt_user, alt_worker, alt_api to alt_app;

create schema if not exists alt;
revoke all on schema alt from public;
grant usage on schema alt to alt_user, alt_worker, alt_api;

-- ------------------------------------------------------------------ organisations and people
create table if not exists alt.institutions (
  id smallint primary key,
  key text unique not null,
  name text not null,
  kind text not null check (kind in ('school', 'university', 'corporate')),
  city text,
  serves_minors boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists alt.cohorts (
  id smallint primary key,
  institution_id smallint not null references alt.institutions,
  key text not null,
  name text not null,
  exam text not null default 'ielts_academic' check (exam in ('ielts_academic', 'ielts_general')),
  target_overall numeric(2,1) not null check (target_overall between 1 and 9),
  target_min_skill numeric(2,1) not null check (target_min_skill between 1 and 9),
  deadline date not null,
  weekly_capacity int not null default 8 check (weekly_capacity > 0),   -- 1:1 coaching slots a week
  unique (institution_id, key)
);

create table if not exists alt.profiles (
  user_id uuid primary key references auth.users on delete cascade,
  email text not null,
  role text not null check (role in ('platform', 'inst_admin', 'teacher', 'student')),
  institution_id smallint references alt.institutions,
  display_name text not null,
  created_at timestamptz not null default now(),
  check ((role = 'platform') = (institution_id is null))
);

create table if not exists alt.teacher_cohorts (
  user_id uuid not null references alt.profiles on delete cascade,
  cohort_id smallint not null references alt.cohorts,
  primary key (user_id, cohort_id)
);

create table if not exists alt.students (
  id int generated by default as identity primary key,
  institution_id smallint not null references alt.institutions,
  cohort_id smallint not null references alt.cohorts,
  external_ref text not null,                  -- learner id in the prep platform
  display_name text not null,
  birth_year smallint check (birth_year between 1940 and 2020),
  user_id uuid unique references auth.users on delete set null,
  synthetic_engagement text,                   -- demo data only: how the generator made this learner
  created_at timestamptz not null default now(),
  erased_at timestamptz,
  unique (institution_id, external_ref)
);
create index if not exists students_cohort on alt.students (cohort_id);

-- Consent is per purpose. For minors the guardian grants it; we keep only a hash of the evidence.
create table if not exists alt.consents (
  id bigint generated always as identity primary key,
  student_id int not null references alt.students on delete cascade,
  kind text not null check (kind in ('guardian', 'self')),
  scope text not null check (scope in ('ai_feedback', 'audio_retention', 'share_with_institution')),
  granted_at timestamptz not null default now(),
  revoked_at timestamptz,
  evidence_sha256 text not null check (evidence_sha256 ~ '^[0-9a-f]{64}$')
);
create unique index if not exists consents_one_active on alt.consents (student_id, scope) where revoked_at is null;

-- ------------------------------------------------------------------ learning evidence
-- Every band observation (practice, mock, AI-scored writing / speaking), partitioned by month.
create table if not exists alt.attempts (
  id bigint generated always as identity,
  student_id int not null references alt.students on delete cascade,
  skill text not null check (skill in ('reading', 'listening', 'writing', 'speaking')),
  source text not null check (source in ('practice', 'mock', 'ai_writing', 'ai_speaking')),
  band numeric(2,1) not null check (band between 0 and 9),
  raw_score smallint check (raw_score between 0 and 40),
  taken_at timestamptz not null,
  essay_id uuid,
  via text not null default 'seed' check (via in ('seed', 'api', 'app', 'worker')),
  created_at timestamptz not null default now(),
  primary key (id, taken_at)
) partition by range (taken_at);
create unique index if not exists attempts_essay on alt.attempts (essay_id, taken_at);
create index if not exists attempts_student on alt.attempts (student_id, taken_at);

do $$
declare m date := date '2026-05-01';
begin
  while m < date '2027-07-01' loop
    execute format('create table if not exists alt.attempts_%s partition of alt.attempts for values from (%L) to (%L)',
                   to_char(m, 'YYYY_MM'), m, (m + interval '1 month')::date);
    m := (m + interval '1 month')::date;
  end loop;
  execute 'create table if not exists alt.attempts_default partition of alt.attempts default';
end $$;

create table if not exists alt.prompts (
  id int generated by default as identity primary key,
  task text not null default 'task2' check (task in ('task2')),
  body text not null,
  question_type text not null,
  source text not null,
  body_sha256 text unique not null
);

create table if not exists alt.essays (
  id uuid primary key default gen_random_uuid(),
  student_id int not null references alt.students on delete cascade,
  prompt_id int not null references alt.prompts,
  body text,                                   -- null after the retention purge or an erasure request
  word_count int not null check (word_count >= 0),
  body_sha256 text not null,
  submitted_at timestamptz not null default now(),
  status text not null default 'queued' check (status in ('queued', 'scored', 'failed')),
  via text not null check (via in ('seed', 'api', 'app')),
  corpus_ref text,                             -- id in the public essay corpus (seed only)
  purged_at timestamptz
);
create index if not exists essays_student on alt.essays (student_id, submitted_at desc);
create index if not exists essays_queued on alt.essays (submitted_at) where status = 'queued';

-- Bitemporal: a re-score (new model) closes the old row; exactly one current score per essay.
create table if not exists alt.essay_scores (
  id bigint generated always as identity primary key,
  essay_id uuid not null references alt.essays on delete cascade,
  model_version text not null,
  tr numeric(2,1) not null, cc numeric(2,1) not null, lr numeric(2,1) not null, gra numeric(2,1) not null,
  overall numeric(2,1) not null,
  overall_raw double precision not null,
  lo80 numeric(2,1) not null, hi80 numeric(2,1) not null,
  flags text[] not null default '{}',
  drivers jsonb not null,
  scored_by text not null,
  valid_from timestamptz not null default now(),
  valid_to timestamptz
);
create unique index if not exists essay_scores_one_current on alt.essay_scores (essay_id) where valid_to is null;

create table if not exists alt.essay_feedback (
  id bigint generated always as identity primary key,
  essay_id uuid not null references alt.essays on delete cascade,
  lang text not null check (lang in ('en', 'id')),
  source text not null check (source in ('llm', 'rules')),
  model text,
  content jsonb not null,
  dropped int not null default 0,              -- items removed by the grounding check
  created_by uuid,
  created_at timestamptz not null default now()
);
create index if not exists essay_feedback_essay on alt.essay_feedback (essay_id, created_at desc);

-- Human review: a random audit slice (unbiased agreement estimate) plus low-confidence essays.
create table if not exists alt.review_queue (
  essay_id uuid primary key references alt.essays on delete cascade,
  reason text not null check (reason in ('random_audit', 'low_confidence', 'appeal')),
  queued_at timestamptz not null default now(),
  done_at timestamptz
);

-- Append-only, hash-chained ledger of teacher scores.
create table if not exists alt.reviews (
  seq bigint primary key,
  essay_id uuid not null references alt.essays,
  reviewer uuid not null,
  reason text not null,
  tr numeric(2,1) not null, cc numeric(2,1) not null, lr numeric(2,1) not null, gra numeric(2,1) not null,
  overall numeric(2,1) not null,
  ai_overall numeric(2,1),                     -- AI score in force when the teacher scored
  ai_model_version text,
  note text,
  created_at timestamptz not null default now(),
  prev_hash text not null,
  hash text not null unique
);

create table if not exists alt.official_results (
  id int generated always as identity primary key,
  student_id int not null references alt.students on delete cascade,
  test_date date not null,
  reading numeric(2,1) not null, listening numeric(2,1) not null, writing numeric(2,1) not null, speaking numeric(2,1) not null,
  overall numeric(2,1) not null,
  verified text not null check (verified in ('self_reported', 'trf_verified')),
  via text not null default 'seed' check (via in ('seed', 'api', 'app')),
  created_at timestamptz not null default now(),
  unique (student_id, test_date)
);

-- Bitemporal readiness snapshots; one current row per learner.
create table if not exists alt.readiness (
  id bigint generated always as identity primary key,
  student_id int not null references alt.students on delete cascade,
  model_version text not null,
  calibration_id int,
  status text not null check (status in ('on_track', 'watch', 'at_risk', 'insufficient_data')),
  p_target double precision,
  p_overall double precision,
  overall_now numeric(2,1),
  overall_at_deadline double precision,
  weeks_left double precision not null,
  binding text,
  priority double precision not null,
  recoverable boolean not null,
  skills jsonb not null,
  computed_by text not null,
  valid_from timestamptz not null default now(),
  valid_to timestamptz
);
create unique index if not exists readiness_one_current on alt.readiness (student_id) where valid_to is null;

-- Coalescing: many score events for one learner become one readiness job.
create table if not exists alt.readiness_pending (
  student_id int primary key references alt.students on delete cascade,
  queued_at timestamptz not null default now()
);

create table if not exists alt.calibrations (
  id int generated always as identity primary key,
  entries jsonb not null,                      -- {"writing:ai_writing": {"a": -0.27, "b": 1, "n": 139}, ...}
  evaluation jsonb not null,
  active boolean not null default false,
  created_by uuid,
  created_at timestamptz not null default now()
);
create unique index if not exists calibrations_one_active on alt.calibrations (active) where active;

create table if not exists alt.models (
  version text primary key,
  kind text not null check (kind in ('writing', 'readiness')),
  metrics jsonb not null,
  artifact_sha256 text,
  created_at timestamptz not null default now()
);

create table if not exists alt.reports (
  id bigint generated always as identity primary key,
  cohort_id smallint not null references alt.cohorts,
  lang text not null check (lang in ('en', 'id')),
  facts jsonb not null,
  content jsonb not null,
  source text not null check (source in ('llm', 'rules')),
  dropped int not null default 0,
  created_by uuid not null,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------------ operations and governance
create table if not exists alt.api_keys (
  id int generated always as identity primary key,
  institution_id smallint not null references alt.institutions,
  prefix text unique not null,
  key_sha256 text unique not null,
  label text not null,
  created_by uuid,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at timestamptz
);

create table if not exists alt.idempotency (
  institution_id smallint not null,
  key text not null,
  request_sha256 text not null,
  status int not null,
  response jsonb not null,
  created_at timestamptz not null default now(),
  primary key (institution_id, key)
);

create table if not exists alt.audit_log (
  seq bigint primary key,
  at timestamptz not null default now(),
  actor uuid,
  actor_kind text not null check (actor_kind in ('user', 'api', 'worker', 'system')),
  action text not null,
  target text,
  detail jsonb not null default '{}',
  prev_hash text not null,
  hash text not null unique
);

create table if not exists alt.rate_limits (key text primary key, window_start timestamptz not null, hits int not null);
create table if not exists alt.token_buckets (key text primary key, tokens double precision not null, updated_at timestamptz not null);

create table if not exists alt.worker_runs (
  id bigint generated always as identity primary key,
  worker text not null,
  trigger text not null,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  processed int,
  failed int
);
create index if not exists worker_runs_started on alt.worker_runs (started_at desc);

create table if not exists alt.settings (key text primary key, value text not null);

create table if not exists alt.retention_policies (
  data_kind text primary key,
  keep_days int not null check (keep_days > 0),
  keep_days_minor int not null check (keep_days_minor > 0),
  basis text not null,
  action text not null
);

create table if not exists alt.purge_runs (
  id bigint generated always as identity primary key,
  ran_at timestamptz not null default now(),
  data_kind text not null,
  rows int not null,
  trigger text not null
);

create table if not exists alt.dsr_requests (
  id int generated always as identity primary key,
  student_id int not null references alt.students,
  kind text not null check (kind in ('export', 'erase')),
  requested_by uuid not null,
  status text not null default 'open' check (status in ('open', 'done', 'rejected')),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  result jsonb
);

create table if not exists alt.llm_log (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  purpose text not null,
  model text,
  prompt_sha256 text not null,
  ms int,
  ok boolean not null,
  dropped int not null default 0,
  user_id uuid
);

create table if not exists alt.load_tests (
  id int generated always as identity primary key,
  n int not null,
  started_at timestamptz not null default now(),
  created_by uuid
);
